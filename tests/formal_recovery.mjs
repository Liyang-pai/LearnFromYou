// 真实协议的失败/恢复投影，不访问网络或调用模型。
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const source=await readFile(new URL('../frontend/formal/service.js',import.meta.url),'utf8');
const {emptySession,applyEvent,retrySession,retryPending,canRetry}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const s=emptySession(),emit=(type,data)=>applyEvent(s,{type,data});
emit('ready',{session_id:'112233aabbcc',muted:false});
emit('error',{message:'普通课堂错误',retryable:false});
emit('resume_response',{status:'failed',message:'恢复请求失败',retryable:true});
emit('knowledge_review',{status:'failed',targets:['k1','k2'],message:'第一组复核失败',retryable:true});
emit('knowledge_review',{status:'failed',targets:['k3'],message:'第二组复核失败',retryable:true});
assert.equal(s.error,'普通课堂错误');assert.equal(canRetry(s),true);
assert.throws(()=>retrySession(s,()=>{throw Error('发送失败');}),/发送失败/);
assert.equal(s.recovery.resume.status,'failed');assert.equal(s.recovery.knowledge.k1.status,'failed');assert.equal(canRetry(s),true);
let sends=0;
assert.equal(retrySession(s,e=>{assert.deepEqual(e,{type:'retry'});sends++;}),true);
assert.equal(retrySession(s,()=>sends++),false);assert.equal(sends,1);assert.equal(retryPending(s),true);
assert.equal(s.recovery.resume.error,'恢复请求失败');assert.equal(s.error,'普通课堂错误');
emit('resume_response',{status:'running'});assert.equal(s.recovery.resume.error,'恢复请求失败');
emit('resume_response',{status:'generated'});assert.equal(s.recovery.resume,null);assert.equal(retryPending(s),true);
emit('knowledge_review',{status:'running',targets:['k1','k2']});
emit('knowledge_review',{status:'completed',targets:['k1','k2']});
assert.deepEqual(Object.keys(s.recovery.knowledge),['k3']);assert.equal(retryPending(s),true);
emit('knowledge_review',{status:'failed',targets:['k3'],message:'再次失败',retryable:true});
assert.equal(canRetry(s),true);assert.equal(s.error,'普通课堂错误');
retrySession(s,()=>sends++);emit('knowledge_review',{status:'stale',targets:['k3']});assert.equal(retryPending(s),true);
emit('state',{state:{pending_reviews:[]}});assert.deepEqual(s.recovery.knowledge,{});assert.equal(retryPending(s),false);
emit('resume_response',{status:'failed',message:'再次恢复失败',retryable:true});
emit('mute',{muted:true});assert.equal(s.recovery.resume.status,'paused');assert.equal(!!canRetry(s),false);
emit('resume_response',{status:'running'});assert.equal(s.recovery.resume.status,'paused');
emit('mute',{muted:false});assert.equal(s.recovery.resume.status,'queued');
emit('resume_response',{status:'skipped'});assert.equal(s.recovery.resume,null);
// 旧批次完成不能清掉恢复错误或后来发生的其他错误。
emit('teacher_batch',{batch_id:'batch1',request_count:1,processing_status:'failed'});
emit('error',{code:'model_failure',message:'讲授处理失败',retryable:true});
retrySession(s,()=>sends++);assert.equal(s.batchRetryPending,true);
emit('error',{message:'后来发生的录音错误',retryable:false});
emit('teacher_batch',{batch_id:'batch1',request_count:2,processing_status:'processed'});
assert.equal(s.error,'后来发生的录音错误');assert.equal(s.batchRetryPending,false);
emit('error',{code:'model_failure',message:'讲授再次失败',retryable:true});retrySession(s,()=>sends++);
emit('teacher_batch',{batch_id:'batch1',request_count:3,processing_status:'processed'});assert.equal(s.error,'');assert.equal(s.retryable,false);
emit('knowledge_review',{status:'failed',targets:['k4'],message:'待重试',retryable:true});
s.active=false;assert.equal(!!canRetry(s),false);assert.equal(retrySession(s,()=>sends++),false);
s.active=true;s.ending=true;assert.equal(!!canRetry(s),false);
emit('finished',{});assert.equal(s.recovery.knowledge.k4.error,'待重试');assert.equal(!!canRetry(s),false);
const failed=emptySession();failed.starting=true;failed.draft='文字草稿';
